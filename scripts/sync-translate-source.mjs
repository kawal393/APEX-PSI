// Copies the English site text and language list into the translate function,
// so the server translates only its own copy (never text supplied by a visitor).
// Run: node scripts/sync-translate-source.mjs
import { readFileSync, writeFileSync } from "node:fs";

const en = JSON.parse(readFileSync("src/i18n/locales/en.json", "utf8"));
const idx = readFileSync("src/i18n/index.ts", "utf8");
const block = idx.slice(idx.indexOf("export const LANGUAGES"), idx.indexOf("};", idx.indexOf("export const LANGUAGES")));
const langs = {};
for (const m of block.matchAll(/^\s*'?([A-Za-z-]+)'?:\s*\{\s*name:\s*'([^']+)'/gm)) {
  if (m[1] !== "en") langs[m[1]] = m[2];
}
const out = `// Generated by scripts/sync-translate-source.mjs — do not edit by hand.
export const EN_SOURCE: Record<string, unknown> = ${JSON.stringify(en, null, 2)};

export const TARGET_LANGUAGES: Record<string, string> = ${JSON.stringify(langs, null, 2)};
`;
writeFileSync("supabase/functions/translate/source.ts", out);
console.log(`translate/source.ts: ${Object.keys(langs).length} languages`);
