/*
 * Writes public/SELF_AUDIT.md from the machine record produced by registry-self-audit.mjs.
 * Every number is read out of the JSON the audit wrote; nothing here is typed by hand, so the
 * served page cannot drift from the run that produced it without the run being re-executed.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const S = join(homedir(), ".openhands", "scratch");
const SITE = join(homedir(), ".openhands", "apex-infra-site", "public", "SELF_AUDIT.md");
const need = (f) => {
  const p = join(S, f);
  if (!existsSync(p)) {
    console.log(`BROKEN — ${p} is missing. Run scripts/registry-self-audit.mjs first; this page is generated, not written.`);
    process.exit(2);
  }
  return JSON.parse(readFileSync(p, "utf8"));
};
const audit = need("self_audit.json");
const rows = need("registry_all.json");
const flagged = need("flagged.json");

const F = rows.filter((r) => r.finding_severity && r.finding_severity !== "none");
const isVendor = (r) => /cross-source|market data feed|data vendor|market data/i.test(`${r.metric} ${r.apex_recomputation} ${r.finding}`);
const zeroFlagged = F.filter((r) => /^0(\.0+)?%$/.test(String(r.variance || "")));
const zeroHard = zeroFlagged.filter((r) => ["discrepancy", "material"].includes(r.finding_severity));
const vendorMat = flagged.filter((r) => r.finding_severity === "material" && /cross-source|market data feed/i.test(`${r.metric} ${r.finding}`));
const noFiling = F.filter((r) => !/SEC EDGAR|ASX|10-K|EDGAR/i.test(r.verify_label || ""));
const yahoo = rows.filter((r) => /yahoo/i.test(r.verify_label || ""));
const companies = new Set(rows.map((r) => r.ticker)).size;
const leafless = rows.filter((r) => !r.psi_merkle_leaf).length;
const stamp = audit.read_at ? new Date(audit.read_at).toISOString().slice(0, 10) : "unknown date";

const md = `# Apex self-audit — our own arithmetic, re-done by machine

Read at: ${stamp}. Generated by \`scripts/registry-self-audit.mjs\` in the APEX-PSI repository. The file
you are reading is produced from that run's machine record; no number below is entered by hand.

## What this page is for

Every other registry in this field asks to be believed. We would rather show the re-check.

A machine read **all ${audit.rows.toLocaleString()} rows** of the reconciliation registry — not a sample, the
whole table, confirmed against the row count the site's own statistics view declares. For each row it
re-did the arithmetic using only the figures printed inside that same row, then asked whether the row's
printed answer follows.

- Rows the machine could re-compute: **${(audit.tally.PASS + audit.tally.FAIL).toLocaleString()} of ${audit.rows.toLocaleString()}** (${(((audit.tally.PASS + audit.tally.FAIL) / audit.rows) * 100).toFixed(1)}%)
- Rows whose arithmetic **holds**: **${audit.tally.PASS.toLocaleString()}**
- Rows whose arithmetic **does not hold**: **${audit.tally.FAIL.toLocaleString()}**
- Rows the machine declined to judge: **${audit.tally.UNCHECKED.toLocaleString()}** — with the reason named below, and never counted as a pass

Within the ${F.length.toLocaleString()} rows published as findings, **${flagged.length ? audit.flagged.PASS.toLocaleString() : 0} re-computed clean and ${audit.flagged.FAIL} did not hold**.

## The checker is tested against known-wrong rows

A checker that has never said no proves nothing. Four rows whose arithmetic fits on one line — three
deliberately wrong, one correct — go through the same function as the live registry. The run is only
accepted when all four are judged correctly. This run caught 4 of 4.

## What we found about ourselves, stated plainly

1. **${vendorMat.length} of the 5 rows we label "material" are not findings about a company.** They compare the filed
   document to a third-party market data feed. Where the two disagree, the filed document governs, and our
   own finding text says so. Our published doctrine is that a difference between two sources is published
   as a difference, never as an allegation — these ${vendorMat.length} rows should carry a different tier, and this page is
   where we say so before anyone else does.
2. **${zeroHard.length} rows are flagged as a discrepancy or worse while printing a variance of 0%.** The flag and the number
   in the same row contradict each other. ${zeroFlagged.length} rows print 0% variance in total; ${zeroFlagged.length - zeroHard.length} of those are the informational
   "note" tier, where a zero variance is not a contradiction.
3. **${noFiling.length} of the ${F.length.toLocaleString()} published findings cannot back the word "filings"** — they cite a market data page
   (${yahoo.length.toLocaleString()} rows across the whole registry cite Yahoo Finance; ${rows.filter((r) => !r.verify_label).length.toLocaleString()} name no source at all) — while the
   headline says every figure is "recomputed from source filings, cited and sealed".
4. **${leafless.toLocaleString()} of ${audit.rows.toLocaleString()} rows carry a SHA-256 seal but no PSI merkle leaf.** Every one of the ${F.length.toLocaleString()} rows
   published as a finding does carry a leaf, so the sentence on the homepage holds for the findings it speaks
   about. The gap is in the clean rows, and it is named here rather than hidden by the word "sealed".

## The honest ceiling of this audit

The machine only judges a row when the row prints both of its own figures in a form it can read. Where it
declined, it says why:

${Object.entries(audit.reasons || {}).map(([k, v]) => `- ${v} rows — ${k}`).join("\n") || `- see the machine record for the per-row reasons`}

Raising that coverage is the point of the next runs, not a defect in the rows.

## How to re-do this yourself

\`\`\`
cd ~/openhands/psi-hub-merge
node scripts/registry-self-audit.mjs
\`\`\`

It reads the live registry through the same public address the website uses, needs no account, changes
nothing, and exits non-zero if any row stops agreeing with itself or if the checker misses a planted error.
`;

writeFileSync(SITE, md);
console.log(`WROTE ${SITE}\n`);
console.log(md);
